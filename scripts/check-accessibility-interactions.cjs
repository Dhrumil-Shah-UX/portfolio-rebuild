const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(path.join(process.env.TEMP, 'portfolio-a11y-tools/node_modules/playwright'));
const { default: AxeBuilder } = require(path.join(process.env.TEMP, 'portfolio-a11y-tools/node_modules/@axe-core/playwright'));
const routes = require('../scripts/seo-render').pageData().pages;
const results = [];
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', args: ['--no-sandbox', '--disable-gpu'] });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  async function visit(route) {
    await page.goto('http://127.0.0.1:3087' + route, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => typeof appBootstrapped !== 'undefined' && appBootstrapped && document.querySelector('.page-back-wrap'));
  }
  await visit('/');
  await page.keyboard.press('Tab');
  assert.equal(await page.locator('.skip-link').evaluate(el => el === document.activeElement), true);
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(() => document.activeElement.id), 'main-content');
  results.push('Skip link is the first tab stop and moves focus to main content.');
  await page.locator('.hero-cta-primary').focus();
  await page.keyboard.press('Enter');
  await page.waitForURL('**/work');
  await page.waitForFunction(() => document.activeElement?.tagName === 'H1');
  results.push('Keyboard route navigation focuses the destination heading.');
  await page.setViewportSize({ width: 320, height: 740 });
  await page.locator('.menu-toggle').focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('.menu-toggle').getAttribute('aria-expanded'), 'true');
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(() => document.activeElement.closest('nav')?.id), 'primary-navigation');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.menu-toggle').getAttribute('aria-expanded'), 'false');
  assert.equal(await page.locator('.menu-toggle').evaluate(el => el === document.activeElement), true);
  results.push('Mobile menu opens with Enter, receives keyboard focus, and closes with Escape with focus restored.');
  await visit('/work/azhartt-accessibility');
  const opener = page.locator('[data-ac-image]').first();
  await opener.focus();
  await page.keyboard.press('Enter');
  await page.waitForSelector('.ac-modal[open]');
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(() => !!document.activeElement.closest('dialog[open]')), true);
  const modalAudit = await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
  results.push({ state: 'accessibility image dialog', violations: modalAudit.violations.map(v => ({ id: v.id, targets: v.nodes.map(n => n.target) })) });
  await page.keyboard.press('Escape');
  assert.equal(await opener.evaluate(el => el === document.activeElement), true);
  results.push('Image dialog supports keyboard opening, focus containment, Escape, and return to opener.');
  await page.locator('.ac-table-wrap').focus();
  await page.keyboard.press('ArrowRight');
  results.push('Audit table can receive keyboard focus and arrow scrolling.');
  await visit('/ai-lab');
  assert.equal(await page.locator('.ai-process-phase').first().evaluate(el => getComputedStyle(el, '::after').animationName), 'none');
  await page.locator('.ai-process-label').nth(2).focus();
  assert.equal(await page.locator('#ai-phase-prototype').evaluate(el => getComputedStyle(el).visibility), 'visible');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#ai-phase-prototype').evaluate(el => getComputedStyle(el).visibility), 'hidden');
  results.push('Reduced motion disables phase pulsing. Phase details open on focus and dismiss with Escape.');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.locator('.ai-process-motion-toggle').click();
  assert.equal(await page.locator('.ai-process-phase').first().evaluate(el => getComputedStyle(el, '::after').animationPlayState), 'paused');
  results.push('Animation pause control stops the phase halos.');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.locator('.preview-motion-toggle').first().click();
  assert.match(await page.locator('.preview-motion-toggle').first().getAttribute('aria-label'), /Pause preview/);
  await page.locator('.preview-motion-toggle').first().click();
  assert.match(await page.locator('.preview-motion-toggle').first().getAttribute('aria-label'), /Play preview/);
  results.push('Project preview control exposes matching Play/Pause preview labels.');
  for (const [id, route] of Object.entries(routes)) {
    await page.setViewportSize({ width: 1280, height: 900 });
    await visit(route.path);
    const media = await page.locator('.page.is-visible video').evaluateAll(videos => videos.map(video => ({ paused: video.paused, autoplay: video.autoplay })));
    const sizes = await page.evaluate(() => {
      const heading = document.querySelector('.page.is-visible h1');
      const original = getComputedStyle(heading).fontSize;
      document.documentElement.style.zoom = '2';
      const enlarged = getComputedStyle(heading).fontSize;
      return { original, enlarged, overflow: document.documentElement.scrollWidth - innerWidth };
    });
    results.push({ id, check: '200% CSS zoom simulation at 1280px (640px layout)', ...sizes, media });
    await page.evaluate(() => { document.documentElement.style.zoom = ''; });
    await page.setViewportSize({ width: 320, height: 740 });
    await page.addStyleTag({ content: '* { line-height: 1.5 !important; letter-spacing: .12em !important; word-spacing: .16em !important; } p { margin-bottom: 2em !important; }' });
    results.push({ id, check: 'WCAG text spacing at 320px', overflow: await page.evaluate(() => document.documentElement.scrollWidth - innerWidth) });
  }
  await page.goto('http://127.0.0.1:3087/404.html');
  const missing = await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
  results.push({ state: '404 page', violations: missing.violations.map(v => v.id) });
  results.push({ browserErrors: errors });
  fs.writeFileSync('accessibility-interactions.json', JSON.stringify(results, null, 2));
  console.log(JSON.stringify(results, null, 2));
  await browser.close();
})().catch(error => { console.error(error); fs.writeFileSync('accessibility-interactions.json', JSON.stringify({ results, error: error.message }, null, 2)); process.exit(1); });
